#!/bin/bash
# Canonical Nginx vhost for apex marketing + IAM API on shuleplus.rw (auth-web :6100, auth-api :4001).
# Regenerate on every Authentication deploy so /_next/static CSS never hits the wrong upstream.
#
# Usage: sudo bash scripts/generate-shuleplus-apex-nginx.sh
set -uo pipefail

REPO="${REPO:-/root/apps/shuleplus/ShulePlus}"
CERT_DIR="${CERT_DIR:-/etc/letsencrypt/live/shuleplus.rw}"
AUTH_WEB_PORT="${AUTH_WEB_PORT:-6100}"
AUTH_API_PORT="${AUTH_API_PORT:-4001}"
MAINT_DIR="${MAINT_DIR:-/var/www/shuleplus/maintenance}"
CONF="/etc/nginx/sites-available/shuleplus-auth.conf"

read -r -d '' MAINT_BLOCK <<'MAINT_EOF' || true
    if (-f MAINT_DIR_PLACEHOLDER/ON) {
        return 503;
    }
    error_page 503 @maintenance;
    location @maintenance {
        root MAINT_DIR_PLACEHOLDER;
        rewrite ^ /index.html break;
    }

MAINT_EOF
MAINT_BLOCK="${MAINT_BLOCK//MAINT_DIR_PLACEHOLDER/$MAINT_DIR}"

PROXY_NEXT="        proxy_pass http://127.0.0.1:${AUTH_WEB_PORT};
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_cache_bypass \$http_upgrade;"

cat > "$CONF" <<EOF
# Generated by $REPO/scripts/generate-shuleplus-apex-nginx.sh — do not hand-edit; re-run the script.
server {
    listen 80;
    server_name shuleplus.rw www.shuleplus.rw;
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl;
    server_name shuleplus.rw www.shuleplus.rw;
    ssl_certificate ${CERT_DIR}/fullchain.pem;
    ssl_certificate_key ${CERT_DIR}/privkey.pem;
${MAINT_BLOCK}
    client_max_body_size 25m;

    # Next.js hashed assets — must reach auth-web (not API, not HTML fallback)
    location ^~ /_next/ {
${PROXY_NEXT}
        add_header Cache-Control "public, max-age=31536000, immutable";
    }

    location ^~ /uploads/ {
        proxy_pass http://127.0.0.1:${AUTH_API_PORT};
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        client_max_body_size 25m;
    }

    location ^~ /api/ {
        proxy_pass http://127.0.0.1:${AUTH_API_PORT};
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 120s;
        client_max_body_size 25m;
    }

    location / {
${PROXY_NEXT}
    }
}
EOF

ln -sf "$CONF" /etc/nginx/sites-enabled/shuleplus-auth.conf
nginx -t && systemctl reload nginx
echo "Wrote $CONF (apex → auth-web:${AUTH_WEB_PORT}, /api + /uploads → auth-api:${AUTH_API_PORT})"
