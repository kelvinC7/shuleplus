export const PROTECTED_POSITIONS = ['Organization Administrator', 'School Manager'] as const;

export function isProtectedEmployee(emp: { isProtected?: boolean; position?: string }): boolean {
  if (emp.isProtected) return true;
  return PROTECTED_POSITIONS.some(
    (p) => p.toLowerCase() === (emp.position ?? '').toLowerCase()
  );
}

