import jsPDF from 'jspdf';
import { autoTable as autoTableFn } from 'jspdf-autotable';
import * as XLSX from 'xlsx';

export interface ExportColumn {
  header: string;
  accessor: string;
}

export interface ExportOptions {
  title: string;
  columns: ExportColumn[];
  data: Record<string, unknown>[];
  fileName?: string;
  userName?: string;
  orientation?: 'portrait' | 'landscape';
}

function formatDate(): string {
  return new Date().toLocaleString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

function sanitizeFileName(name: string): string {
  return name.replace(/[^a-zA-Z0-9_-]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');
}

function getValueString(value: unknown): string {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') return JSON.stringify(value);
  return String(value);
}

const FALLBACK_LOGO = `data:image/svg+xml;base64,${btoa(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><rect width="48" height="48" rx="12" fill="#FCB038"/><text x="24" y="30" text-anchor="middle" fill="#000435" font-size="20" font-weight="bold">S+</text></svg>`)}`;

async function loadLogo(): Promise<string> {
  try {
    const res = await fetch('/yellow-icon.png');
    const blob = await res.blob();
    return await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(reader.result as string);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });
  } catch {
    return FALLBACK_LOGO;
  }
}

export async function exportToPdf(options: ExportOptions): Promise<void> {
  const { title, columns, data, userName, orientation } = options;
  const logoBase64 = await loadLogo();
  const isLandscape = orientation === 'landscape';
  const doc = new jsPDF({
    orientation: isLandscape ? 'landscape' : 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;
  const navyColor: [number, number, number] = [0, 4, 53];
  const grayColor: [number, number, number] = [100, 116, 139];
  let currentPage = 1;
  const dateStr = formatDate();

  const drawHeader = () => {
    try {
      doc.addImage(logoBase64, 'PNG', margin, 10, 14, 14);
    } catch {
      /* ignore */
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(navyColor[0], navyColor[1], navyColor[2]);
    doc.text(title, margin + 18, 16);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(grayColor[0], grayColor[1], grayColor[2]);
    doc.text(dateStr, pageWidth - margin - doc.getTextWidth(dateStr), 16);
    if (userName) {
      const issuerText = `Issued by: ${userName}`;
      doc.text(issuerText, pageWidth - margin - doc.getTextWidth(issuerText), 21);
    }
    doc.setDrawColor(252, 176, 56);
    doc.setLineWidth(0.5);
    doc.line(margin, userName ? 26 : 22, pageWidth - margin, userName ? 26 : 22);
  };

  const drawFooter = () => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(grayColor[0], grayColor[1], grayColor[2]);
    doc.text('Generated by Shule+ School Budget', margin, pageHeight - 8);
    doc.text(`Page ${currentPage}`, pageWidth - margin - 10, pageHeight - 8);
  };

  autoTableFn(doc, {
    head: [columns.map((c) => c.header)],
    body: data.map((row) => columns.map((col) => getValueString(row[col.accessor]))),
    startY: userName ? 32 : 28,
    margin: { top: userName ? 32 : 28, bottom: 16, left: margin, right: margin },
    tableWidth: contentWidth,
    headStyles: { fillColor: navyColor, textColor: [255, 255, 255], fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    didDrawPage: () => {
      drawFooter();
      currentPage++;
      drawHeader();
    },
  });

  doc.save(`${sanitizeFileName(options.fileName ?? title)}_${new Date().toISOString().split('T')[0]}.pdf`);
}

export function exportToExcel(options: ExportOptions): void {
  const { title, columns, data } = options;
  const wb = XLSX.utils.book_new();
  const headers = columns.map((c) => c.header);
  const rows = data.map((row) => columns.map((col) => row[col.accessor] ?? ''));
  const ws = XLSX.utils.aoa_to_sheet([[title], [], headers, ...rows]);
  XLSX.utils.book_append_sheet(wb, ws, 'Report');
  XLSX.writeFile(wb, `${sanitizeFileName(options.fileName ?? title)}_${new Date().toISOString().split('T')[0]}.xlsx`);
}
