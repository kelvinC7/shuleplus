export function normalizeTransportLocale(raw?: string | null): TransportLocale {
  const v = (raw ?? 'en').toLowerCase();
  if (v === 'rw' || v.startsWith('rw') || v === 'kin') return 'rw';
  if (v === 'fr' || v.startsWith('fr')) return 'fr';
  return 'en';
}

export function transportT(locale: TransportLocale, key: string): string {
  return dict[locale][key] ?? dict.en[key] ?? key;
}

