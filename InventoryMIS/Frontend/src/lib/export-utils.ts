async function loadLogo(): Promise<string> {
  try {
    const res = await fetch('/logo.png')
    const blob = await res.blob()
    return await new Promise((resolve, reject) => {
      const reader = new FileReader()
      reader.onloadend = () => resolve(reader.result as string)
      reader.onerror = reject
      reader.readAsDataURL(blob)
    })
  } catch {
    return FALLBACK_LOGO
  }
}

export async function exportToPdf(options: ExportOptions): Promise<void> {
  const { title, columns, data, userName, orientation } = options
  const logoBase64 = await loadLogo()

  const isLandscape = orientation === "landscape"
  const doc = new jsPDF({
    orientation: isLandscape ? "landscape" : "portrait",
    unit: "mm",
    format: "a4",
  })

  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 15
  const contentWidth = pageWidth - margin * 2

  const primaryColor: [number, number, number] = [252, 176, 56]
  const navyColor: [number, number, number] = [0, 4, 53]
  const grayColor: [number, number, number] = [100, 116, 139]

  let currentPage = 1
  const dateStr = formatDate()

  const drawHeader = () => {
    try {
      doc.addImage(logoBase64, "PNG", margin, 10, 40, 15)
    } catch {
      doc.setFillColor(252, 176, 56)
      doc.roundedRect(margin, 10, 12, 12, 2, 2, "F")
      doc.setFont("helvetica", "bold")
      doc.setFontSize(8)
      doc.setTextColor(0, 4, 53)
      doc.text("S", margin + 4, 19)
    }

    doc.setFont("helvetica", "bold")
    doc.setFontSize(11)
    doc.setTextColor(navyColor[0], navyColor[1], navyColor[2])
    const titleX = pageWidth - margin - doc.getTextWidth(title)
    doc.text(title, titleX, 16)

    doc.setFont("helvetica", "normal")
    doc.setFontSize(8)
    doc.setTextColor(grayColor[0], grayColor[1], grayColor[2])
    doc.text(dateStr, pageWidth - margin - doc.getTextWidth(dateStr), 21)

    if (userName) {
      const issuerText = `Issued by: ${userName}`
      doc.text(issuerText, pageWidth - margin - doc.getTextWidth(issuerText), 26)
    }

    doc.setDrawColor(primaryColor[0], primaryColor[1], primaryColor[2])
    doc.setLineWidth(0.5)
    const sepY = userName ? 31 : 26
    doc.line(margin, sepY, pageWidth - margin, sepY)
  }

  const drawFooter = () => {
    doc.setDrawColor(primaryColor[0], primaryColor[1], primaryColor[2])
    doc.setLineWidth(0.3)
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12)

    doc.setFont("helvetica", "normal")
    doc.setFontSize(8)
    doc.setTextColor(grayColor[0], grayColor[1], grayColor[2])
    doc.text("Generated by Shuleplus", margin, pageHeight - 5)

    doc.text(`Page ${currentPage}`, pageWidth - margin - 10, pageHeight - 5)
  }

  const tableRows = data.map((row) =>
    columns.map((col) => getValueString(row[col.accessor]))
  )

  const tableHeaders = columns.map((col) => col.header)

  const headerEndY = userName ? 37 : 32

  autoTableFn(doc, {
    head: [tableHeaders],
    body: tableRows,
    startY: headerEndY,
    margin: { top: headerEndY, bottom: 18, left: margin, right: margin },
    tableWidth: contentWidth,
    styles: {
      font: "helvetica",
      fontSize: 8,
      textColor: [33, 33, 33],
      lineColor: [200, 200, 200],
      lineWidth: 0.1,
    },
    headStyles: {
      fillColor: navyColor,
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 9,
      halign: "left",
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {},
    didParseCell: (data: any) => {
      if (data.section === "body" && data.column.dataKey !== undefined) {
        const header = tableHeaders[data.column.dataKey]
        if (header?.toLowerCase().includes("amount") || header?.toLowerCase().includes("salary") || header?.toLowerCase().includes("price") || header?.toLowerCase().includes("total") || header?.toLowerCase().includes("fee") || header?.toLowerCase().includes("cost") || header?.toLowerCase().includes("payment")) {
          data.cell.styles.halign = "right"
        }
        if (header?.toLowerCase().includes("status") || header?.toLowerCase().includes("type") || header?.toLowerCase().includes("role")) {
          data.cell.styles.halign = "center"
        }
      }
    },
    didDrawPage: (_data: any) => {
      drawFooter()
      currentPage++
      drawHeader()
    },
  })

  doc.save(`${sanitizeFileName(title)}_${new Date().toISOString().split("T")[0]}.pdf`)
}

export function exportToExcel(options: ExportOptions): void {
  const { title, columns, data, userName } = options

  const wb = XLSX.utils.book_new()

  const dateStr = formatDate()

  const metaData: (string | undefined)[][] = [
    [title],
    [],
    ["Exported by:", userName || "N/A"],
    ["Date:", dateStr],
    [],
  ]

  const headers = columns.map((col) => col.header)
  const rows = data.map((row) =>
    columns.map((col) => {
      const value = row[col.accessor]
      return value ?? ""
    })
  )

  const wsData = [...metaData, ...headers.map((h) => [h]), ...rows.map((r) => [...r])]

  const ws = XLSX.utils.aoa_to_sheet(wsData)

  ws["!cols"] = columns.map((_, idx) => {
    const maxLen = Math.max(
      columns[idx].header.length,
      ...data.map((row) => {
        const val = getValueString(row[columns[idx].accessor])
        return val.length
      }),
      10
    )
    return { wch: Math.min(Math.max(maxLen + 3, 12), 50) }
  })

  if (!ws["!merges"]) ws["!merges"] = []
  ws["!merges"].push({ s: { r: 0, c: 0 }, e: { r: 0, c: columns.length - 1 } })

  const headerRowIndex = metaData.length
  const range = XLSX.utils.decode_range(ws["!ref"] || "A1:A1")

  for (let C = range.s.c; C <= range.e.c; C++) {
    const headerRef = XLSX.utils.encode_cell({ r: headerRowIndex, c: C })
    if (!ws[headerRef]) continue
    const cell = ws[headerRef]
    cell.s = {
      font: { bold: true, color: { rgb: "FFFFFF" }, sz: 11 },
      fill: { fgColor: { rgb: "000435" } },
      alignment: { horizontal: "left", vertical: "center" },
      border: {
        bottom: { style: "medium", color: { rgb: "000435" } },
        top: { style: "medium", color: { rgb: "000435" } },
        left: { style: "thin", color: { rgb: "CCCCCC" } },
        right: { style: "thin", color: { rgb: "CCCCCC" } },
      },
    }
  }

  for (let R = headerRowIndex + 1; R <= range.e.r; R++) {
    for (let C = range.s.c; C <= range.e.c; C++) {
      const ref = XLSX.utils.encode_cell({ r: R, c: C })
      if (!ws[ref]) continue
      const cell = ws[ref]
      const header = columns[C]?.header?.toLowerCase() || ""

      cell.s = {
        alignment: {
          horizontal:
            header.includes("amount") ||
            header.includes("salary") ||
            header.includes("price") ||
            header.includes("total") ||
            header.includes("fee") ||
            header.includes("cost") ||
            header.includes("payment")
              ? "right"
              : header.includes("status") || header.includes("type") || header.includes("role")
                ? "center"
                : "left",
          vertical: "center",
        },
        border: {
          bottom: { style: "thin", color: { rgb: "EEEEEE" } },
          left: { style: "thin", color: { rgb: "EEEEEE" } },
          right: { style: "thin", color: { rgb: "EEEEEE" } },
        },
      }

      if ((R - headerRowIndex) % 2 === 0) {
        cell.s.fill = { fgColor: { rgb: "F8FAFC" } }
      }

      if (typeof cell.v === "number") {
        cell.t = "n"
        if (header.includes("amount") || header.includes("salary") || header.includes("price") || header.includes("total") || header.includes("fee") || header.includes("cost") || header.includes("payment")) {
          cell.z = '#,##0.00'
        }
      }
    }
  }

  const titleRef = XLSX.utils.encode_cell({ r: 0, c: 0 })
  if (ws[titleRef]) {
    ws[titleRef].s = {
      font: { bold: true, color: { rgb: "000435" }, sz: 14 },
      alignment: { horizontal: "left", vertical: "center" },
    }
  }

  XLSX.utils.book_append_sheet(wb, ws, "Report")

  const fileName = `${sanitizeFileName(title)}_${new Date().toISOString().split("T")[0]}.xlsx`
  XLSX.writeFile(wb, fileName)
}
